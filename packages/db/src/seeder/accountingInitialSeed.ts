async function main() {
  const { companyCode, companyName, legalName } =
    await readSeedInputsFromTerminal();

  const existingCompany = await db.company.findFirst({
    where: { code: companyCode },
    select: { id: true, code: true, name: true },
  });

  if (existingCompany) {
    throw new Error(
      `Company already exists for code=${companyCode}. Aborting to avoid duplicate seed.`
    );
  }

  await db.$transaction(async (tx) => {
    const companyIdMap = new Map<number, number>();
    const financialYearIdMap = new Map<number, number>();
    const groupIdMap = new Map<number, number>();
    const voucherTypeIdMap = new Map<number, number>();
    const ledgerIdMap = new Map<number, number>();

    const company = await tx.company.create({
      data: {
        code: companyCode,
        name: companyName,
        legalName,
        status: COMPANY_ROW.status as Status,
        booksBeginFrom: toDate(COMPANY_ROW.booksBeginFrom)!,
      },
    });
    companyIdMap.set(COMPANY_ROW.id, company.id);

    for (const row of COMPANY_ADDRESS_ROWS) {
      await tx.companyAddress.create({
        data: {
          companyId: requireMappedId(
            companyIdMap,
            row.companyId,
            "company address companyId"
          ),
          addressType: row.addressType as AddressType,
          addressLine1: row.addressLine1,
          addressLine2: row.addressLine2,
          cityId: row.cityId,
          stateId: row.stateId,
          countryId: row.countryId,
          pinCode: row.pinCode,
          phoneNumber: row.phoneNumber,
          email: row.email,
          isDefault: row.isDefault,
        },
      });
    }

    for (const row of COMPANY_STATUTORY_ROWS) {
      await tx.companyStatutory.create({
        data: {
          companyId: requireMappedId(
            companyIdMap,
            row.companyId,
            "company statutory companyId"
          ),
          pan: row.pan,
          gstin: row.gstin,
          cin: row.cin,
          tan: row.tan,
          msmeNo: row.msmeNo,
          gstRegistrationType: row.gstRegistrationType as GstRegistrationType,
          gstStateCode: row.gstStateCode,
          isGstEnabled: row.isGstEnabled,
          gstEffectiveFrom: toDate(row.gstEffectiveFrom),
        },
      });
    }

    for (const row of COMPANY_FEATURE_ROWS) {
      await tx.companyFeatures.create({
        data: {
          companyId: requireMappedId(
            companyIdMap,
            row.companyId,
            "company features companyId"
          ),
          enableCostCenter: row.enableCostCenter,
          enableBillWiseTracking: row.enableBillWiseTracking,
          enableBankReconciliation: row.enableBankReconciliation,
          enableGst: row.enableGst,
        },
      });
    }

    for (const row of COMPANY_FINANCIAL_YEAR_ROWS) {
      const created = await tx.companyFinancialYear.create({
        data: {
          companyId: requireMappedId(
            companyIdMap,
            row.companyId,
            "financial year companyId"
          ),
          fyName: row.fyName,
          startDate: toDate(row.startDate)!,
          endDate: toDate(row.endDate)!,
          booksBeginFrom: toDate(row.booksBeginFrom)!,
          isCurrent: row.isCurrent,
          isLocked: row.isLocked,
        },
      });
      financialYearIdMap.set(row.id, created.id);
    }

    const pendingGroups = [...GROUP_ROWS];
    while (pendingGroups.length > 0) {
      const before = pendingGroups.length;

      for (let index = pendingGroups.length - 1; index >= 0; index--) {
        const row = pendingGroups[index];
        if (row.parentId && !groupIdMap.has(row.parentId)) continue;

        const created = await tx.group.create({
          data: {
            companyId: requireMappedId(
              companyIdMap,
              row.companyId,
              "group companyId"
            ),
            name: row.name,
            alias: row.alias,
            isPrimaryGroup: row.isPrimaryGroup,
            parentId: row.parentId
              ? requireMappedId(groupIdMap, row.parentId, "group parentId")
              : null,
            primaryCategory: row.primaryCategory as AccountingPrimaryCategory,
            reportType: row.reportType as AccountingReportType,
            nature: row.nature as AccountingNature,
            affectsGrossProfit: row.affectsGrossProfit,
            behavesLikeSubLedger: row.behavesLikeSubLedger,
            netDrCrForReporting: row.netDrCrForReporting,
            usedForCalculation: row.usedForCalculation,
            isReserved: row.isReserved,
          },
        });

        groupIdMap.set(row.id, created.id);
        pendingGroups.splice(index, 1);
      }

      if (pendingGroups.length === before) {
        throw new Error(
          `Unable to resolve group parent mapping. Pending old group ids: ${pendingGroups
            .map((g) => g.id)
            .join(", ")}`
        );
      }
    }

    for (const row of VOUCHER_TYPE_ROWS) {
      const created = await tx.voucherType.create({
        data: {
          companyId: requireMappedId(
            companyIdMap,
            row.companyId,
            "voucher type companyId"
          ),
          name: row.name,
          nature: row.nature as VoucherTypeNature,
          numberingMode: row.numberingMode as VoucherNumberingMode,
          isNarrationMandatory: row.isNarrationMandatory,
          allowZeroValueTransactions: row.allowZeroValueTransactions,
          requireBankOrCash: row.requireBankOrCash,
          contraOnlyBankOrCash: row.contraOnlyBankOrCash,
          enableBillWiseTracking: row.enableBillWiseTracking,
          enableCostCenters: row.enableCostCenters,
          isReserved: row.isReserved,
        },
      });
      voucherTypeIdMap.set(row.id, created.id);
    }

    for (const row of LEDGER_ROWS) {
      const created = await tx.ledger.create({
        data: {
          companyId: requireMappedId(
            companyIdMap,
            row.companyId,
            "ledger companyId"
          ),
          groupId: requireMappedId(groupIdMap, row.groupId, "ledger groupId"),
          name: row.name,
          alias: row.alias,
          ledgerType: row.ledgerType as LedgerType,
          isBillWiseOn: row.isBillWiseOn,
          isCostCentreOn: row.isCostCentreOn,
          isBankAccount: row.isBankAccount,
          isCashAccount: row.isCashAccount,
          isReserved: row.isReserved,
          bankName: row.bankName,
          bankIfsc: row.bankIfsc,
          bankAccountNo: row.bankAccountNo,
          upiId: row.upiId,
          contactName: row.contactName,
          phone: row.phone,
          email: row.email,
          address: row.address,
          gstType: row.gstType as LedgerGstType,
          gstin: row.gstin,
          placeOfSupplyStateId: row.placeOfSupplyStateId,
        },
      });
      ledgerIdMap.set(row.id, created.id);
    }

    for (const row of ACCOUNTING_INTEGRATION_CONFIG_ROWS) {
      const details = ACCOUNTING_INTEGRATION_CONFIG_DETAIL_ROWS.filter(
        (detail) => detail.accountingIntegrationConfigId === row.id
      );

      await tx.accountingIntegrationConfig.create({
        data: {
          refType: row.refType as VoucherReferenceType,
          subRefType: row.subRefType as ConfigSubRefType,
          voucherTypeId: requireMappedId(
            voucherTypeIdMap,
            row.voucherTypeId as number,
            "integration config voucherTypeId"
          ),
          narrationText: row.narrationText,
          accountingIntegrationConfigDetails: {
            create: details.map((detail) => {
              const mappedLedgerValue =
                detail.ledgerType === "ID"
                  ? String(
                      requireMappedId(
                        ledgerIdMap,
                        Number(detail.ledgerValue),
                        "integration detail ledgerValue"
                      )
                    )
                  : detail.ledgerValue;

              return {
                type: detail.type as ConfigType,
                ledgerType: detail.ledgerType as ConfigLedgerType,
                ledgerValue: mappedLedgerValue,
                policy: detail.policy as DrCr,
                amountKey: detail.amountKey,
                masterKey: detail.masterKey,
                groupId: detail.groupId
                  ? requireMappedId(
                      groupIdMap,
                      detail.groupId,
                      "integration detail groupId"
                    )
                  : null,
                isPaymentRelated: detail.isPaymentRelated,
              };
            }),
          },
        },
      });
    }

    for (const row of UIN_CONFIG) {
      await tx.accUINConfig.create({
        data: {
          ...row,
          shortCode: row.shortCode as AccUinShortCode,
          seqResetPolicy: row.seqResetPolicy as UIN_RESET_POLICY,
          seqResetDate: new Date(row.seqResetDate),
        },
      });
    }
    await tx.accSettings.create({
      data: {
        ...SETTINGS,
        calculationMethod: SETTINGS.calculationMethod as CalculationMethod,
        roundingMethod: SETTINGS.roundingMethod as RoundFormat,
      },
    });

    console.log("Accounting seed completed", {
      "Company ID": company.id,
      "Company Code": company.code,
      "Company Name": company.name,
      "Company Legal Name": company.legalName,
      "Company Status": company.status,
      "Company Books Begin From": company.booksBeginFrom,
      "No. of financialYears": COMPANY_FINANCIAL_YEAR_ROWS.length,
      "No. of groups": GROUP_ROWS.length,
      "No. of voucherTypes": VOUCHER_TYPE_ROWS.length,
      "No. of ledgers": LEDGER_ROWS.length,
      "No. of integrationConfigs": ACCOUNTING_INTEGRATION_CONFIG_ROWS.length,
      "No. of integrationConfigDetails":
        ACCOUNTING_INTEGRATION_CONFIG_DETAIL_ROWS.length,
      "No. of UIN Configs": UIN_CONFIG.length,
      "No. of settings": 1,
    });
  });
}

main()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await db.$disconnect();
  });
